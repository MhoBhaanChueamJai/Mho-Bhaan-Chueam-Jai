/** อายุสมุฏฐาน: ปฐมวัย (แรกเกิด–16) เสมหะ · มัชฌิมวัย (16–32) ปิตตะ · ปัจฉิมวัย (32 ขึ้นไป) วาตะ */
export function ageSamutthan(age: number) {
  if (age < 16) return { stage: 'ปฐมวัย', range: 'แรกเกิด – 16 ปี', dosha: 'เสมหะ (ธาตุน้ำ)', el: 'น้ำ' as El, note: 'วัยนี้ป่วยด้วยเสมหะ หวัด น้ำมูก ได้ง่าย' };
  if (age < 32) return { stage: 'มัชฌิมวัย', range: '16 – 32 ปี', dosha: 'ปิตตะ (ธาตุไฟ)', el: 'ไฟ' as El, note: 'วัยนี้ป่วยด้วยความร้อน ไข้ ร้อนใน ได้ง่าย' };
  return { stage: 'ปัจฉิมวัย', range: '32 ปีขึ้นไป', dosha: 'วาตะ (ธาตุลม)', el: 'ลม' as El, note: 'วัยนี้ป่วยด้วยลม ปวดเมื่อย ท้องอืด นอนไม่หลับ ได้ง่าย' };
}

/** อุตุสมุฏฐาน (ฤดู 3): คิมหันต์ 16 ก.พ.–15 มิ.ย. · วสันต์ 16 มิ.ย.–15 ต.ค. · เหมันต์ 16 ต.ค.–15 ก.พ. */
export function seasonNow(d = new Date()) {
  const m = d.getMonth() + 1, day = d.getDate();
  const md = m * 100 + day;
  if (md >= 216 && md <= 615) return { name: 'ฤดูร้อน (คิมหันต์)', dosha: 'ปิตตะ (ธาตุไฟ)', el: 'ไฟ' as El, tip: 'ระวังความร้อน ดื่มน้ำมาก เลือกรสขม เย็น' };
  if (md >= 616 && md <= 1015) return { name: 'ฤดูฝน (วสันต์)', dosha: 'วาตะ (ธาตุลม)', el: 'ลม' as El, tip: 'ระวังลมกำเริบ ปวดเมื่อย เลือกรสเผ็ดร้อน' };
  return { name: 'ฤดูหนาว (เหมันต์)', dosha: 'เสมหะ (ธาตุน้ำ)', el: 'น้ำ' as El, tip: 'ระวังหวัด เสมหะ เลือกรสขม เปรี้ยว' };
}
