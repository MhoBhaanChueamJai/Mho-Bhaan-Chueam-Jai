const flat = (s: string) => s.replace(/\s+/g, '');

/** ขยายคำค้น: คำถามเดิม + คำมาตรฐานของอาการที่จับได้ (ไม่ซ้ำ) */
export function expandQuery(q: string): string {
  const f = flat(q);
  const add = new Set<string>();
  for (const [say, std] of MAP) if (say.some((w) => f.includes(w))) std.split(' ').forEach((x) => !f.includes(x) && add.add(x));
  return add.size ? `${q} ${[...add].join(' ')}` : q;
}
