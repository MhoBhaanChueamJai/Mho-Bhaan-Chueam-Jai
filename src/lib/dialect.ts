/** คำจากคลังที่ภาษากลางปรากฏในข้อความนี้ (ยาวก่อน · ไม่เกิน max คู่) */
function lexHits(d: Exclude<Dialect, 'central'>, text: string, max = 24): string {
  const hits = LEXICON[d].filter(([c]) => c.length >= 2 && text.includes(c)).sort((a, b) => b[0].length - a[0].length);
  return hits.slice(0, max).map(([c, x]) => `${c}→${x}`).join(' · ');
}

const guideText = (d: Exclude<Dialect, 'central'>, text = '') => {
  const g = GUIDE[d];
  const extra = text ? lexHits(d, text) : '';
  return `คำแทนภาษากลาง: ${g.words}${extra ? `\nคำเพิ่มจากพจนานุกรมภาษาถิ่น (ตรงกับข้อความนี้): ${extra}` : ''}\nหลักเสียงและจังหวะ: ${g.sound}\nคำลงท้าย: ${g.endings}\nตัวอย่าง (กลาง → ${g.name}):\n${g.examples.map(([a, b]) => `• "${a}" → "${b}"`).join('\n')}`;
};

/** ข้อความแนบให้ AI: ผู้ใช้พูดภาษาถิ่นอะไร (ใช้ตีความ) */
export function dialectHint(): string {
  if (current === 'central') return 'ผู้ใช้พูดภาษาไทยกลางเป็นหลัก แต่อาจมีคำภาษาถิ่นปน ให้ตีความจากบริบท';
  const g = GUIDE[current];
  return `ผู้ใช้พูด${g.name}เป็นหลัก ตีความเป็นภาษาไทยกลางให้ถูกต้อง (คำที่พบบ่อย: ${g.words.split(' · ').slice(0, 14).join(' · ')})`;
}

