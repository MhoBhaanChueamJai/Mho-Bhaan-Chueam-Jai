/** ภาษาที่หมอใช้คุยกับครูปัญญา (ตั้งในหน้าตั้งค่า) — ใช้บอก AI ให้ฟังและตีความได้แม่นขึ้น */
export type Dialect = 'central' | 'isan' | 'north' | 'south';

export const DIALECTS: { id: Dialect; label: string; note: string }[] = [
  { id: 'central', label: 'ภาษากลาง', note: 'ภาษาไทยกลาง' },
  { id: 'isan', label: 'อีสาน', note: 'ภาษาอีสาน / ลาว' },
  { id: 'north', label: 'เหนือ', note: 'คำเมือง' },
  { id: 'south', label: 'ใต้', note: 'ภาษาใต้' },
];

let current: Dialect = 'central';
export const setDialect = (d: Dialect) => {
  current = d;
};
export const getDialect = () => current;

/** ข้อความแนบให้ AI: ผู้พูดใช้ภาษาถิ่นอะไร */
export function dialectHint(): string {
  switch (current) {
    case 'isan':
      return 'หมอพูดภาษาอีสาน (ลาว) เป็นหลัก เช่น บ่ = ไม่, แม่น = ใช่, เจ็บแอว = ปวดเอว, เป็นหยัง = เป็นอะไร, หลาย = มาก ตีความเป็นภาษาไทยกลางให้ถูกต้อง';
    case 'north':
      return 'หมอพูดคำเมือง (ภาษาเหนือ) เป็นหลัก เช่น บ่ = ไม่, เจ้า = ครับ/ค่ะ, ปวดหัว = เจ็บหัว, กิ๋น = กิน, ลำ = อร่อย ตีความเป็นภาษาไทยกลางให้ถูกต้อง';
    case 'south':
      return 'หมอพูดภาษาใต้เป็นหลัก เช่น ไม่หอ = ไม่มี, หรอย = อร่อย, แหลง = พูด, ม่าย = ไม่ ตีความเป็นภาษาไทยกลางให้ถูกต้อง';
    default:
      return 'หมอพูดภาษาไทยกลางเป็นหลัก แต่อาจมีคำภาษาถิ่นปน ให้ตีความจากบริบท';
  }
}

/** วิธีพูดตอบให้เหมือนคนภาคนั้น (คำศัพท์ คำลงท้าย จังหวะประโยค) */
export function dialectSpeakStyle(): string {
  switch (current) {
    case 'isan':
      return 'พูดตอบเป็นภาษาอีสานแบบเจ้าของภาษา เหมือนคนอีสานคุยกันจริง ใช้คำอย่าง บ่, แม่น, เฮ็ด, หยัง, เด้อ, เนาะ, สิ, คือ (=ทำไม/เหมือน), หลาย (=มาก), ข่อย/เพิ่น ลงท้ายสุภาพด้วย "ครับ" หรือ "เด้อครับ" ห้ามแปลงเป็นภาษากลาง';
    case 'north':
      return 'พูดตอบเป็นคำเมือง (ภาษาเหนือ) แบบเจ้าของภาษา เหมือนคนเชียงใหม่คุยกันจริง ใช้คำอย่าง บ่, ก่, เน้อ, เจ้า, อะหยัง, กิ๋น, ปั๋น, หื้อ, จ้วย, ลำ, ขะใจ๋ ลงท้ายสุภาพด้วย "ครับ" หรือ "เน้อครับ" ห้ามแปลงเป็นภาษากลาง';
    case 'south':
      return 'พูดตอบเป็นภาษาใต้แบบเจ้าของภาษา เหมือนคนใต้คุยกันจริง ใช้คำอย่าง หนิ, โหล, แหละ, ม่าย, แหลง, ไหร, หรอย, หลาว (=เร็ว), พรือ, ตะ ลงท้ายสุภาพด้วย "ครับ" หรือ "ครับโหล" ห้ามแปลงเป็นภาษากลาง';
    default:
      return 'พูดตอบเป็นภาษาไทยกลาง ภาษาพูดเป็นธรรมชาติ ลงท้าย "ครับ"';
  }
}

/** คำเปิดของครูปัญญาตามภาษาพูด */
export function dialectGreeting(): string {
  switch (current) {
    case 'isan':
      return 'สวัสดีครับ ข่อยครูปัญญาเด้อ เดี๋ยวสิช่วยซักประวัติให้เด้อครับ';
    case 'north':
      return 'สวัสดีครับ ผมครูปัญญาเน้อ เดี๋ยวจะจ้วยซักประวัติหื้อเน้อครับ';
    case 'south':
      return 'สวัสดีครับ ผมครูปัญญาหนิ เดี๋ยวช่วยซักประวัติให้โหลครับ';
    default:
      return 'สวัสดีครับ ผมครูปัญญานะครับ เดี๋ยวผมช่วยซักประวัติให้นะครับ';
  }
}
